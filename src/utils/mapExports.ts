import type { CampusBuilding, CampusProfile, FloorZone, UniversityProfile } from '../data/campusData.ts';
import { buildingOccupancy } from './campusLogic.ts';

const campusCenters: Record<string, [number, number]> = {
  'ucl-bloomsbury': [-.1340, 51.5246], 'ucl-east': [-.0087, 51.5381],
  'kcl-strand': [-.1163, 51.5115], 'kcl-waterloo-guys': [-.1122, 51.5040],
  'imperial-south-ken': [-.1749, 51.4988], 'imperial-white-city': [-.2363, 51.5162],
  'lse-aldwych': [-.1160, 51.5144],
};

export function campusGeoJson(campus: CampusProfile): object {
  const [centerLng, centerLat] = campusCenters[campus.id] ?? [-.13, 51.52];
  const coordinates = (x: number, z: number): [number, number] => [
    Number((centerLng + x / 69000).toFixed(7)), Number((centerLat - z / 111000).toFixed(7)),
  ];
  return {
    type: 'FeatureCollection',
    metadata: { name: campus.name, source: campus.sourceUrl, geometry: 'schematic, not a survey' },
    features: campus.buildings.map(building => {
      const [x, z] = building.position;
      const [w, , d] = building.dimensions;
      const ring = [coordinates(x - w / 2, z - d / 2), coordinates(x + w / 2, z - d / 2), coordinates(x + w / 2, z + d / 2), coordinates(x - w / 2, z + d / 2)];
      return { type: 'Feature', properties: { name: building.name, code: building.shortCode, height_estimate_m: building.dimensions[1], schematic: true }, geometry: { type: 'Polygon', coordinates: [[...ring, ring[0]]] } };
    }),
  };
}

export function downloadBlob(data: BlobPart, mime: string, filename: string): void {
  const objectUrl = URL.createObjectURL(new Blob([data], { type: mime }));
  const anchor = document.createElement('a');
  anchor.href = objectUrl;
  anchor.download = filename;
  anchor.click();
  setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);
}

function pdfText(text: string): string {
  return text.normalize('NFKD').replace(/[^\x20-\x7E]/g, ' ').replace(/[()\\]/g, character => `\\${character}`);
}

export function campusPdf(university: UniversityProfile, campus: CampusProfile, hour: number): Uint8Array {
  const lines: string[] = [
    '0.98 0.98 0.97 rg 0 0 842 595 re f',
    '0.11 0.13 0.17 rg',
    `BT /F1 21 Tf 40 548 Td (${pdfText(university.name)}) Tj ET`,
    `BT /F1 12 Tf 40 525 Td (${pdfText(`${campus.name}  |  schematic campus map`)}) Tj ET`,
    '0.93 0.94 0.93 rg 40 75 490 425 re f',
    '0.8 0.82 0.8 RG 1 w 40 75 490 425 re S',
  ];
  for (const building of campus.buildings) {
    const [x, z] = building.position;
    const [w, , d] = building.dimensions;
    const px = 282 + x * 3.1;
    const py = 285 - z * 3.1;
    lines.push('0.68 0.72 0.63 rg');
    lines.push(`${(px - w * 1.55).toFixed(1)} ${(py - d * 1.55).toFixed(1)} ${(w * 3.1).toFixed(1)} ${(d * 3.1).toFixed(1)} re f`);
    lines.push('0.12 0.16 0.13 rg');
    lines.push(`BT /F1 8 Tf ${(px - 9).toFixed(1)} ${(py - 2).toFixed(1)} Td (${pdfText(building.shortCode)}) Tj ET`);
  }
  lines.push('0.12 0.15 0.18 rg BT /F1 10 Tf 555 480 Td (BUILDING SCHEDULE) Tj ET');
  campus.buildings.forEach((building, index) => {
    const y = 455 - index * 49;
    lines.push(`BT /F1 9 Tf 555 ${y} Td (${pdfText(`${building.shortCode}  ${building.name}`)}) Tj ET`);
    lines.push(`BT /F1 8 Tf 555 ${y - 14} Td (${pdfText(`${building.floors.length} floors | ${buildingOccupancy(building, hour)}% estimated occupied`)}) Tj ET`);
  });
  lines.push(`BT /F1 8 Tf 40 45 Td (${pdfText(`Generated by CampusExplorer | ${campus.sourceUrl}`)}) Tj ET`);
  lines.push('BT /F1 8 Tf 40 30 Td (Geometry and availability are estimates. Verify with the university before travelling.) Tj ET');
  const stream = lines.join('\n') + '\n';
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 842 595] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${new TextEncoder().encode(stream).length} >>\nstream\n${stream}endstream`,
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  objects.forEach((object, index) => { offsets.push(new TextEncoder().encode(pdf).length); pdf += `${index + 1} 0 obj\n${object}\nendobj\n`; });
  const xref = new TextEncoder().encode(pdf).length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.slice(1).forEach(offset => { pdf += `${String(offset).padStart(10, '0')} 00000 n \n`; });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new TextEncoder().encode(pdf);
}

export function parseBlueprint(raw: string, index: number): CampusBuilding {
  let input: Record<string, unknown>;
  try { input = JSON.parse(raw) as Record<string, unknown>; } catch { throw new Error('Enter valid JSON building data.'); }
  if (typeof input.name !== 'string' || !input.name.trim()) throw new Error('A building name is required.');
  const name = input.name.trim().slice(0, 60);
  const position = Array.isArray(input.position) ? input.position : [30 + index * 5, -28 + index * 3];
  const dimensions = Array.isArray(input.dimensions) ? input.dimensions : [14, 16, 12];
  const floorsInput = Array.isArray(input.floors) ? input.floors : [];
  const floors: FloorZone[] = floorsInput.length ? floorsInput.slice(0, 10).map((value, i) => {
    const item = value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {};
    const type = item.type === 'Silent' || item.type === 'Group' ? item.type : 'Quiet';
    return { level: String(item.level ?? i + 1).slice(0, 4), name: String(item.name ?? `Floor ${i + 1}`).slice(0, 50), type, seats: Number(item.seats) > 0 ? Math.min(500, Number(item.seats)) : 40, baseOccupancy: .45, noiseDba: type === 'Silent' ? 31 : type === 'Group' ? 52 : 40, sockets: true, water: false, bookable: false };
  }) : [{ level: '1', name: 'Schematic quiet study', type: 'Quiet', seats: 40, baseOccupancy: .4, noiseDba: 40, sockets: true, water: false, bookable: false }];
  const number = (value: unknown, fallback: number, min: number, max: number): number => Number.isFinite(Number(value)) ? Math.min(max, Math.max(min, Number(value))) : fallback;
  return {
    id: `custom-${index}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    name, shortCode: String(input.shortCode ?? name.split(/\s+/).map(word => word[0]).join('')).toUpperCase().slice(0, 4),
    category: 'Imported schematic', position: [number(position[0], 0, -70, 70), number(position[1], 0, -70, 70)],
    dimensions: [number(dimensions[0], 14, 8, 30), number(dimensions[1], 16, 8, 45), number(dimensions[2], 12, 8, 30)],
    style: 'modern', color: '#b7c4b1', hours: [8, 22], hoursLabel: 'Hours unknown (verify)', floors, schematic: true,
  };
}

export function synthesizeBlueprint(description: string, index: number): CampusBuilding {
  const name = description.trim().replace(/\s+/g, ' ').slice(0, 60);
  if (!name) throw new Error('Describe the building to add it to the map.');
  const angle = index * 1.25;
  const position: [number, number] = [Math.round(Math.cos(angle) * 42), Math.round(Math.sin(angle) * 37)];
  const type = /group|collaborat|social/i.test(name) ? 'Group' : 'Quiet';
  return parseBlueprint(JSON.stringify({
    name,
    position,
    dimensions: [15, 18, 13],
    floors: [
      { level: '1', name: 'Study commons', type, seats: 48 },
      { level: '2', name: 'Quiet study', type: 'Quiet', seats: 40 },
      { level: '3', name: 'Silent study', type: 'Silent', seats: 32 },
    ],
  }), index);
}

export function parseGeoJsonBuildings(raw: string, startIndex: number): CampusBuilding[] {
  let input: { type?: string; features?: { type?: string; properties?: Record<string, unknown>; geometry?: { type?: string; coordinates?: unknown } }[] };
  try { input = JSON.parse(raw); } catch { throw new Error('The GeoJSON file is not valid JSON.'); }
  if (!input || input.type !== 'FeatureCollection' || !Array.isArray(input.features)) throw new Error('Upload a GeoJSON FeatureCollection.');
  const polygons = input.features.flatMap(feature => {
    if (!feature || typeof feature !== 'object') return [];
    const coordinates = feature.geometry?.coordinates;
    if (feature.geometry?.type !== 'Polygon' || !Array.isArray(coordinates) || !Array.isArray(coordinates[0])) return [];
    const ring = (coordinates[0] as unknown[]).filter(point => Array.isArray(point) && point.length >= 2 && Number.isFinite(Number(point[0])) && Number.isFinite(Number(point[1]))).map(point => [Number((point as number[])[0]), Number((point as number[])[1])] as [number, number]);
    if (ring.length < 3) return [];
    return [{ ring, name: typeof feature.properties?.name === 'string' ? feature.properties.name : `Imported building ${startIndex + 1}` }];
  }).slice(0, 40);
  if (!polygons.length) throw new Error('No Polygon building footprints were found in this GeoJSON.');
  const all = polygons.flatMap(item => item.ring);
  const lonLat = all.every(([x, y]) => Math.abs(x) <= 180 && Math.abs(y) <= 90);
  const center = [all.reduce((sum, point) => sum + point[0], 0) / all.length, all.reduce((sum, point) => sum + point[1], 0) / all.length];
  const project = ([x, y]: [number, number]): [number, number] => lonLat ? [(x - center[0]) * 69000, -(y - center[1]) * 111000] : [x - center[0], -(y - center[1])];
  const projected = all.map(project);
  const span = Math.max(...projected.map(point => Math.max(Math.abs(point[0]), Math.abs(point[1]))));
  const scale = Math.min(1, 55 / Math.max(1, span));
  return polygons.map((item, index) => {
    const ring = item.ring.map(point => project(point).map(value => value * scale) as [number, number]);
    const x = ring.reduce((sum, point) => sum + point[0], 0) / ring.length;
    const z = ring.reduce((sum, point) => sum + point[1], 0) / ring.length;
    const footprint = ring.map(point => [point[0] - x, point[1] - z] as [number, number]);
    const width = Math.max(...footprint.map(point => point[0])) - Math.min(...footprint.map(point => point[0]));
    const depth = Math.max(...footprint.map(point => point[1])) - Math.min(...footprint.map(point => point[1]));
    const name = item.name.trim().slice(0, 60) || `Imported building ${startIndex + index + 1}`;
    return {
      id: `geo-${startIndex + index}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
      name, shortCode: name.split(/\s+/).map(word => word[0]).join('').slice(0, 4).toUpperCase(), category: 'Imported footprint',
      position: [x, z] as [number, number], dimensions: [Math.max(6, width), 16, Math.max(6, depth)] as [number, number, number],
      style: 'modern' as const, color: '#b7c4b1', hours: [8, 22] as [number, number], hoursLabel: 'Hours unknown (verify)', schematic: true,
      footprint, floors: [{ level: '1', name: 'Imported footprint, study use unverified', type: 'Quiet' as const, seats: 40, baseOccupancy: .45, noiseDba: 40, sockets: false, water: false, bookable: false }],
    };
  });
}
